const imageFile = (categoryId) => {
  const g = group(categoryId)
  if (g === 'skin') return [9, 10].includes(categoryId) ? 'product-serum' : 'product-toner'
  return `product-${g}`
}

export function buildProducts(imageBaseUrl) {
  return rows.map(([brandIdx, categoryId, name, summary, basePrice, skus, saleRate]) => {
    const [how, ingredients] = usage[group(categoryId)]
    const product = {
      brandName: brands[brandIdx].name,
      categoryId,
      name,
      summary,
      description: `${summary} ${how}`,
      ingredients,
      basePrice,
      imageUrls: [`${imageBaseUrl}/demo/${imageFile(categoryId)}.svg`],
      skus,
    }
    if (saleRate) product.saleRate = saleRate
    return product
  })
}

export function buildBanners(imageBaseUrl, now) {
  const at = (ms) => new Date(now.getTime() + ms).toISOString()
  const startsAt = at(-3600e3)
  const endsAt = at(30 * 86400e3)
  const img = (file) => `${imageBaseUrl}/demo/${file}.svg`
  return [
    { title: '듀이 가을 세일', imageUrl: img('banner-sale'), linkUrl: '/products?onSale=true', startsAt, endsAt, sortOrder: 1 },
    { title: '촉촉한 스킨케어 모음', imageUrl: img('banner-skincare'), linkUrl: '/products?categoryId=1', startsAt, endsAt, sortOrder: 2 },
    // 외부 링크 예시다. 이미지는 두 번째 배너와 같이 쓴다.
    { title: '듀이 프로젝트 소개', imageUrl: img('banner-skincare'), linkUrl: 'https://github.com', startsAt, endsAt, sortOrder: 3 },
  ]
}
