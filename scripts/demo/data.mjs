const group = (categoryId) => {
  if (categoryId <= 12) return 'skin'
  if (categoryId <= 15) return 'mask'
  if (categoryId <= 19) return 'cleansing'
  if (categoryId <= 22) return 'sun'
  if (categoryId >= 32) return 'makeup'
  if (categoryId <= 28) return 'body'
  return 'hair'
}

